/** Markdown / JSON report export. */

function line(label, value) {
  return value === null || value === undefined || value === '' ? null : `- **${label}:** ${value}`;
}

export function reportFilename(report, ext) {
  const host = (report.hostname || 'report').replace(/[^a-z0-9.-]/gi, '_');
  const date = new Date(report.analyzedAt || Date.now()).toISOString().slice(0, 10);
  return `deepstack-${host}-${date}.${ext}`;
}

export function toJson(report) {
  return JSON.stringify(report, null, 2);
}

export function toMarkdown(report) {
  const net = report.networkArchitecture || {};
  const sec = report.securityAudit || {};
  const dns = report.dnsInfrastructure;
  const out = [];

  out.push(`# ${report.hostname || report.url} — DeepStack report`, '');
  out.push(`> ${(report.executiveSummary || '').replace(/\*\*/g, '')}`, '');
  out.push(
    ...[
      line('URL', report.url),
      line('Analyzed', new Date(report.analyzedAt || Date.now()).toISOString()),
      line('Rendering', report.internals?.frameworkInternals?.renderingStrategy),
      line('Protocol', (net.protocol || '').toUpperCase()),
      line('Server response (TTFB)', typeof net.ttfbMs === 'number' ? `${net.ttfbMs} ms` : null),
      line('Security grade', sec.grade ? `${sec.grade} (${sec.score}/100)` : null),
      line('Technologies detected', report.totalDetected)
    ].filter(Boolean),
    ''
  );

  out.push('## Technology stack', '');
  for (const cat of report.categories || []) {
    out.push(`### ${cat.label}`, '');
    for (const t of cat.items) {
      const ver = t.version ? ` \`${t.version}\`` : '';
      const proof = t.evidence.map((e) => `${e.type}: ${e.detail}`).join('; ');
      out.push(`- **${t.name}**${ver} — ${t.confidence}% · ${proof}`);
    }
    out.push('');
  }

  if (sec.checks?.length) {
    out.push('## Security checks', '', '| Check | Status | Value |', '| --- | --- | --- |');
    for (const c of sec.checks) out.push(`| ${c.name} | ${c.status} | ${String(c.value).replace(/\|/g, '\\|')} |`);
    const fixes = sec.checks.filter((c) => c.fix);
    if (fixes.length) {
      out.push('', '**Recommended fixes**', '');
      for (const c of fixes) out.push(`- ${c.name}: \`${c.fix}\``);
    }
    out.push('');
  }

  if (net.apiEndpoints?.length) {
    out.push('## API endpoints', '');
    for (const ep of net.apiEndpoints) out.push(`- \`${ep.kind}\` ${ep.host}${ep.path}`);
    out.push('');
  }

  if (dns && (dns.cnameProvider || dns.emailProvider || dns.verifiedServices?.length)) {
    out.push('## DNS', '');
    out.push(
      ...[
        line('Hosting (CNAME)', dns.cnameProvider ? `${dns.cnameProvider.provider} (${dns.cnameProvider.target})` : null),
        line('Email (MX)', dns.emailProvider),
        line('Sending services (SPF)', dns.spfSenders?.join(', ')),
        line('Verified services (TXT)', dns.verifiedServices?.join(', '))
      ].filter(Boolean),
      ''
    );
  }

  if (net.dormantCspHosts?.length) {
    out.push('## Hosts allowed by CSP but not contacted', '', net.dormantCspHosts.map((h) => `\`${h}\``).join(', '), '');
  }

  out.push('---', '_Generated by DeepStack_');
  return out.join('\n');
}
